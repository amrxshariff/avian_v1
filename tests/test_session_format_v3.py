"""
tests/test_session_format_v3.py — P2.10.5: chat history in a saved session.

P2.10.5 is the only P2.10 item that can lose data. A format change that drops
someone's corrections is worse than the fault it fixes, so the version-2
restore test was written first, before the version-3 writer existed, and runs
through the real restore path (_apply_upload) rather than restore() alone.
"""

from __future__ import annotations

import json

from src.dashboard import session_io
from src.dashboard.enrich import KEY_ABOUT, KEY_RESULT, KEY_TITLE
from src.dashboard.notes import NOTES_KEY
from src.dashboard.state import CORRECTIONS_KEY
from tests.test_session_io import make_df


class _Upload:
    def __init__(self, payload: dict):
        self._bytes = json.dumps(payload).encode("utf-8")

    def getvalue(self) -> bytes:
        return self._bytes


class _St:
    def __init__(self):
        self.session_state: dict = {}
        self.errors: list[str] = []

    def error(self, message):
        self.errors.append(message)


# A version-2 file, written out literally. Generated by build_export it would
# become a version-3 file the moment the writer changed, and stop testing this.
V2_FILE = {
    "format_version": 2,
    "app": "network-visualiser",
    "saved_at": "2026-10-09T12:00:00+00:00",
    "corrections": [{"name": "Grace Hopper", "role": "Finance Intern", "soc_major": "13"}],
    "notes": [{"name": "Ada Lovelace", "role": "Data Analyst", "text": "met at kings cross"}],
    "enrichment": {
        "title": "Analyst",
        "about": "I build pricing models for a retail bank and own the forecasting.",
        "result": {"query": "Analyst", "soc_code": None, "soc_major": "15", "occupation": None,
                   "tier": "self_enriched", "score": 0.95, "n_candidates": 1,
                   "major_agreement": 1.0},
        "generated_at": "2026-10-09T12:00:00+00:00",
    },
}


def _restore(payload: dict) -> _St:
    st = _St()
    session_io._apply_upload(st, _Upload(payload), make_df())
    return st


def test_a_version_2_file_restores_corrections_notes_and_profile_intact():
    st = _restore(V2_FILE)

    assert st.errors == []
    assert st.session_state[CORRECTIONS_KEY] == {1: "13"}
    assert st.session_state[NOTES_KEY] == {0: "met at kings cross"}
    assert st.session_state[KEY_TITLE] == "Analyst"
    assert st.session_state[KEY_ABOUT].startswith("I build pricing models")
    assert st.session_state[KEY_RESULT].soc_major == "15"


# --- version 3: the writer, the order, the refusal --------------------------------

from streamlit.testing.v1 import AppTest  # noqa: E402

from src.dashboard.chat import HIGHLIGHT_KEY, HISTORY_KEY  # noqa: E402

THREE = [
    {"role": "user", "text": "first question"}, {"role": "assistant", "text": "answer 1"},
    {"role": "user", "text": "second question"}, {"role": "assistant", "text": "answer 2"},
    {"role": "user", "text": "third question"}, {"role": "assistant", "text": "answer 3"},
]


def _v3_file() -> dict:
    return json.loads(session_io.to_json(session_io.build_export(
        make_df(), {1: "13"}, {0: "met at kings cross"}, chat=THREE)))


def test_the_file_is_version_3():
    assert session_io.FORMAT_VERSION == 3
    assert _v3_file()["format_version"] == 3


def test_the_chat_is_saved_chronologically_not_in_display_order():
    """The file holds storage order. Display order is the renderer's job."""
    assert _v3_file()["chat"] == THREE


def test_a_version_3_file_restores_the_chat_and_everything_else():
    st = _restore(_v3_file())
    assert st.errors == []
    assert st.session_state[HISTORY_KEY] == THREE
    assert st.session_state[HIGHLIGHT_KEY] is None
    assert st.session_state[CORRECTIONS_KEY] == {1: "13"}
    assert st.session_state[NOTES_KEY] == {0: "met at kings cross"}


def test_a_version_2_file_restores_an_empty_chat_with_no_phantom_exchange():
    st = _St()
    st.session_state[HISTORY_KEY] = [{"role": "user", "text": "a live question"}]
    session_io._apply_upload(st, _Upload(V2_FILE), make_df())
    assert st.session_state[HISTORY_KEY] == []


def test_malformed_chat_entries_are_dropped_not_shown():
    payload = _v3_file()
    payload["chat"] = [{"role": "user", "text": "kept"}, {"role": "system", "text": "dropped"},
                       {"role": "assistant"}, "not a turn", {"role": "assistant", "text": "  "}]
    assert session_io.restore_chat(payload) == [{"role": "user", "text": "kept"}]


def test_an_older_build_refuses_a_version_3_file_and_changes_nothing(monkeypatch):
    """A version-2 build must refuse, not read the file partially."""
    v3 = _v3_file()                     # written by this build, before the downgrade
    monkeypatch.setattr(session_io, "FORMAT_VERSION", 2)
    st = _restore(v3)
    assert len(st.errors) == 1 and "newer version" in st.errors[0]
    for key in (CORRECTIONS_KEY, NOTES_KEY, HISTORY_KEY):
        assert key not in st.session_state


def _restored_panel_app():
    import json as _json

    import streamlit as st
    from src.dashboard import session_io as sio
    from src.dashboard.chat import HISTORY_KEY as _HISTORY, render_chat_panel
    from tests.test_assistant import FakeClient, make_df as chat_df

    st.session_state.setdefault(_HISTORY, sio.restore_chat(_json.loads(st.session_state["_file"])))
    render_chat_panel(chat_df(), client=FakeClient([]))


def test_a_restored_chat_renders_newest_first_and_survives_a_rerun(monkeypatch):
    monkeypatch.delenv("ANTHROPIC_API_KEY", raising=False)
    at = AppTest.from_function(_restored_panel_app, default_timeout=30)
    at.session_state["_file"] = json.dumps(_v3_file())
    at.run()

    def shown(at):
        return [(m.name, " ".join(md.value for md in m.markdown)) for m in at.chat_message]

    first = shown(at)
    assert [text for _, text in first] == ["third question", "answer 3", "second question",
                                           "answer 2", "first question", "answer 1"]
    assert shown(at.run()) == first
